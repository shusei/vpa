export function createStatsOrchestration(deps) {
  const {
    CONFIDENCE_INCLUDE_THRESHOLD,
    EPS,
    FORMANT_CONFIDENCE_THRESHOLD,
    FORMANT_MAX_GAP_FRAMES,
    PITCH_COUNTER_KEYS,
    PS_INTERVAL_MS,
    VOLUME_DISPLAY_MODE,
    analysisSession,
    analyzeConnectedSpeech,
    analyzeIntonation,
    analyzeSpeechRate,
    analyzeVowelFocus,
    averageEnergy,
    averageFinite,
    bandOf,
    buildEligibleFrameMask,
    buildFocusInsights,
    categorizeBreathiness,
    categorizeBrightness,
    categorizeTilt,
    cloneOfflineFeatureStore,
    describeResonanceFromEnergy,
    detectVoiceLeaning,
    drawIntonationCurve,
    escapeAttr,
    filterPitchForStats,
    fmt1,
    getSummaryText,
    isDivergent,
    logPostProcessingDiagnostics,
    makeStats,
    notifyInferenceListeners,
    offlineFeatureStore,
    openPracticeCategory,
    percentileSorted,
    pitchPostState,
    psConfidence,
    psDb,
    psHz,
    psHzSmooth,
    psVoiced,
    renderAdvancedSummary,
    renderFocusBlock,
    resizeIntonationCanvas,
    setLatestAnalysisExport,
    setupAdvancedSection,
    setupIntonationLegend,
    sharedComputeAdvancedSummary,
    sharedFinishStreamStats,
    sharedWireAdvancedIntonation,
    summaryString,
    summarizeBreathiness,
    summarizeFormantTrends,
    t,
  } = deps;

  function computeAdvancedSummary() {
    return sharedComputeAdvancedSummary({
      analyzeConnectedSpeech,
      analyzeIntonation,
      analyzeSpeechRate,
      analyzeVowelFocus,
      averageEnergy,
      averageFinite,
      buildEligibleFrameMask,
      categorizeBreathiness,
      categorizeBrightness,
      categorizeTilt,
      describeResonanceFromEnergy,
      detectVoiceLeaning,
      FORMANT_CONFIDENCE_THRESHOLD,
      FORMANT_MAX_GAP_FRAMES,
      lastPf: analysisSession.getLastPf(),
      lastPm: analysisSession.getLastPm(),
      makeStats,
      offlineFeatureStore,
      percentileSorted,
      PS_INTERVAL_MS,
      summarizeBreathiness,
      summarizeFormantTrends,
    });
  }

  function wireAdvancedIntonation(advRoot, advSummary) {
    return sharedWireAdvancedIntonation(advRoot, advSummary, {
      drawIntonationCurve,
      setupIntonationLegend,
    });
  }

  function finishStreamStats() {
    return sharedFinishStreamStats({
      analysisSeq: analysisSession.getAnalysisSeq(),
      bandOf,
      buildEligibleFrameMask,
      buildFocusInsights,
      cloneOfflineFeatureStore,
      computeAdvancedSummary,
      CONFIDENCE_INCLUDE_THRESHOLD,
      currentDevice: analysisSession.getCurrentDevice(),
      drawIntonationCurve,
      EPS,
      escapeAttr,
      filterPitchForStats,
      fmt1,
      FORMANT_CONFIDENCE_THRESHOLD,
      FORMANT_MAX_GAP_FRAMES,
      isDivergent,
      lastPf: analysisSession.getLastPf(),
      lastPm: analysisSession.getLastPm(),
      logPostProcessingDiagnostics,
      makeStats,
      notifyInferenceListeners,
      offlineFeatureStore,
      openPracticeCategory,
      PITCH_COUNTER_KEYS,
      percentileSorted,
      pitchPostState,
      PS_INTERVAL_MS,
      psConfidence,
      psDb,
      psHz,
      psHzSmooth,
      psVoiced,
      renderAdvancedSummary,
      renderFocusBlock,
      resizeIntonationCanvas,
      setLatestAnalysisExport,
      setupAdvancedSection,
      setupIntonationLegend,
      summaryString,
      summaryText: getSummaryText(),
      t,
      VOLUME_DISPLAY_MODE,
      wireAdvancedIntonation,
    });
  }

  return {
    computeAdvancedSummary,
    finishStreamStats,
    wireAdvancedIntonation,
  };
}
